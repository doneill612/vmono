// appPackagesDoc is how to define a package and keep what it says useful.
const appPackagesDoc = `# Packages

## Before creating one

Look at ` + "`vmono ls`" + `: a package that already holds these repositories wants a new
session instead. A package can also be cloned from another with
` + "`vmono package clone`" + `, changing only which members are active, and
` + "`vmono add`" + ` adds a member to one that exists, and so to every session of it.

## What to agree with the user

- **Name**: short, naming the set of repositories or the effort. It cannot be
  changed later.
- **Active members**: only the repositories the work will change.
- **Reference members**: the ones to read, such as shared contracts, a library
  or infrastructure definitions.
- **Purpose**: why these repositories belong together. Every session of the
  package, now and later, reads it, so leave out the task at hand.
- **Roles**: one line each on what a member contributes.

Draft these from what the user told you and what the repositories show, present
them, and create the package with ` + "`vmono new`" + ` once they agree. It can start the
first session at the same time. Longer text can be passed in files.

## Changing what it says

The purpose, context, notes and roles have commands of their own, listed by
` + "`vmono --help`" + `. Name the package, since you are outside its sessions. Prefer
adding a note to rewriting the context: it never loses information. Before
replacing text, read what is there and keep what is still true.

## Exploring the members

` + "`vmono package init`" + ` has a harness read every member and record an overview that
all sessions get. It starts an agent of its own and takes over a terminal, so
suggest that the user runs it; never run it yourself. Commands it suggests for
setting up worktrees are for the user to accept or dismiss.
`

// appSessionsDoc is how to start a piece of work and hand it to the user.
const appSessionsDoc = `# Sessions

## Starting one

Agree on a name for the piece of work, then create it with ` + "`vmono session new`" + `.
The active members' branches are named after it, optionally behind a prefix, so
the name is public: follow the user's branch naming.

- A new branch starts from each member's base, usually the remote's default
  branch as just fetched, not from whatever the user has checked out.
- To stack work on a branch that has not merged, say what to build on. A local
  branch and the remote's branch of the same name are different choices, and may
  be at different commits. The command's help says how to name each; ask if it
  is not clear which the user means.
- To continue work already on a remote, such as an open pull request, vmono has
  to be told to work on that branch. If it stops to say the branch exists, ask
  the user before going ahead. The same goes for taking up a local branch that
  already exists.
- Starting a session fetches the sources and runs the setup commands and hooks
  the user configured, so it can take a while.

If vmono refuses, report the reason as given. Do not work around it, for
instance by removing a branch or a worktree.

## Handing it to the user

Your conversation is not rooted in the new session, so the session's
instructions, vmono skill and harness settings are not loaded here. Tell the user
to open it with ` + "`vmono open`" + `, which starts their harness at the session's
directory, or from the terminal UI. ` + "`vmono shell-init`" + ` gives them a shell function
to change into a session.

` + "`vmono open`" + ` takes over a terminal and starts an agent, so leave it to the user
unless they ask you to run it. Offer to write out what the new session should
know to get started, for them to paste there.

If the user asks you to do the work from here instead, read the session's
` + "`AGENTS.md`" + ` and follow its skill, which ` + "`vmono skill --session`" + ` prints.

## Keeping it current, and finishing

Updating a session, pushing it and what to do once it merges are covered by the
session's own skill. Removing a finished session is for the user.
`
