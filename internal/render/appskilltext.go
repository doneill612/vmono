// appConceptsDoc explains vmono's terms and what lives where.
const appConceptsDoc = `# Concepts

` + "`vmono help concepts`" + ` has the full vocabulary.

- A **package** is defined once: its members, a purpose, free-form context, a
  dated log of notes, and a one-line role per member. It holds no worktrees.
- A **member** is a git repository already on the user's machine. An **active**
  member is checked out on the session's branch, to be changed, committed to
  and pushed. A **reference** member is checked out read-only at a fixed ref,
  under ` + "`_ref/`" + `, to be read.
- A **session** is one piece of work on a package: a directory holding a
  worktree of every member, the active ones all on one branch. A coding harness
  opened at that directory sees all of them. A package can have any number of
  sessions side by side.
- Worktrees share the source repository's objects: nothing is cloned again, and
  what the user has checked out is not touched.
- The package's text is written once and rendered into every session's
  ` + "`AGENTS.md`" + `. What one piece of work is doing stays in that session's
  conversation.

**A new session, not a new package.** More work on the same repositories is a
new session of the package that already holds them. A new package is for a
different set of repositories, or a different reason to group them.

Packages and sessions cannot be renamed, so agree on names before creating them.
`

// appSetupDoc covers installing vmono, its first configuration and how it
// finds repositories.
const appSetupDoc = `# Setting up

## vmono is not installed

If ` + "`vmono`" + ` is not found, check whether it is only missing from ` + "`PATH`" + `: the
installer uses ` + "`~/.local/bin`" + `, or ` + "`%LOCALAPPDATA%\\Programs\\vmono\\bin`" + ` on
Windows. Otherwise give the user the install instructions at
<https://github.com/doneill612/vmono#install> and let them run them. Do not pipe
an install script into a shell unless they ask you to.

## First configuration

vmono needs to know where the user's repositories are. The user can run ` + "`vmono`" + `
in their own terminal, which walks them through setup on first run, or you can
write the configuration with ` + "`vmono init`" + ` once they have told you the
directories. Never guess a directory and write it.

## A repository vmono does not know

` + "`vmono repos`" + ` lists the repositories it knows. A member can also be given as the
path of any git repository on this machine. If a repository is not on the
machine at all, say so: vmono does not clone, and cloning is the user's call.

## Integrations

vmono can open each session in a place of its own in a terminal multiplexer.
` + "`vmono integration ls`" + ` lists what is available. Installing one changes the user's
configuration of that tool, so do it only when asked.

## When something looks wrong

` + "`vmono doctor`" + ` reports drift, and packages or sessions from earlier versions. It
changes things only when asked to fix them: show the user what it found first.
`

