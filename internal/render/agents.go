// Package render generates the files that make a package directory usable
// by a coding harness: the AGENTS.md block, CLAUDE.md, .gitignore, harness
// adapters and the vmono skill, which a harness with a plugin strategy
// (Claude Code) receives as a plugin built around that skill. Everything it
// writes can be rebuilt from the manifest.
package render

import (
	"errors"
	"fmt"
	"path"
	"strings"

	"github.com/doneill612/vmono/internal/manifest"
)

// Markers delimit the part of AGENTS.md that vmono owns. Text outside them
// belongs to the user and survives regeneration.
const (
	BeginMarker = "<!-- vmono:begin -->"
	EndMarker   = "<!-- vmono:end -->"
)

// GeneratedNote is the header vmono puts in files it fully owns.
const GeneratedNote = "generated by vmono"

// AgentsBlock renders the vmono-owned block of AGENTS.md, markers included.
// It is a session's single source of agent context. Everything but the
// branch comes from the package: name and purpose, free-form context, a
// members table, working rules, and recent notes newest first. The branch
// comes from the session.
func AgentsBlock(m *manifest.Manifest, s *manifest.Session) string {
	var b strings.Builder
	b.WriteString(BeginMarker + "\n")
	b.WriteString("<!-- " + GeneratedNote + "; edit with the vmono CLI or TUI. Text between these markers is overwritten. -->\n\n")
	fmt.Fprintf(&b, "# Package: %s · session %s\n\n", m.Name, s.Name)

	b.WriteString("## Purpose\n\n")
	if p := strings.TrimSpace(m.Purpose); p != "" {
		b.WriteString(p + "\n\n")
	} else {
		b.WriteString("_No purpose recorded yet._\n\n")
	}

	if c := strings.TrimSpace(m.Context); c != "" {
		b.WriteString("## Context\n\n" + c + "\n\n")
	}

	b.WriteString("## Members\n\n")
	if len(m.Members) == 0 {
		b.WriteString("_No members yet._\n\n")
	} else {
		b.WriteString("| Path | Mode | Branch / ref | Role |\n| --- | --- | --- | --- |\n")
		for _, mem := range m.Members {
			where := s.Branch
			if mem.Mode == manifest.ModeReference {
				where = mem.Ref
			}
			fmt.Fprintf(&b, "| `%s/` | %s | `%s` | %s |\n",
				path.Clean(strings.ReplaceAll(mem.Path, `\`, "/")), mem.Mode, where, cell(mem.Role))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Working rules\n\n")
	fmt.Fprintf(&b, "- Active members are git worktrees on branch `%s`. Edit and commit in them.\n", s.Branch)
	b.WriteString("- Run git commands from inside the member's directory, never from the package root.\n")
	b.WriteString("- Commit per member; each member is its own repository.\n")
	b.WriteString("- When the user says the work is done, commit in every member and run `vmono session finish`: it lands the commits on each member's own branch in its source repo, locally, and asks first. Never push.\n")
	b.WriteString("- Never edit anything under `_ref/`. Reference members are read-only context.\n")
	b.WriteString("- Each member's own `AGENTS.md` / `CLAUDE.md` still applies inside that member.\n\n")

	if notes := m.RecentNotes(manifest.MaxNotesRendered); len(notes) > 0 {
		b.WriteString("## Notes\n\n")
		for _, n := range notes {
			fmt.Fprintf(&b, "- %s (%s): %s\n", n.At.Format("2006-01-02 15:04"), n.By, oneLine(n.Text))
		}
		b.WriteString("\n")
	}

	b.WriteString(EndMarker + "\n")
	return b.String()
}

// cell makes text safe inside a markdown table cell.
func cell(s string) string {
	s = oneLine(s)
	return strings.ReplaceAll(s, "|", `\|`)
}

// oneLine collapses whitespace runs, including newlines, to single spaces.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// MergeAgents replaces the vmono block inside existing AGENTS.md content,
// keeping everything outside the markers. With no markers the block is
// prepended above any existing text; with empty content the result is just
// the block. A begin marker without a matching end (or the reverse) is an
// error rather than a guess that could eat user text.
func MergeAgents(existing, block string) (string, error) {
	begin := strings.Index(existing, BeginMarker)
	end := strings.Index(existing, EndMarker)
	switch {
	case begin < 0 && end < 0:
		if strings.TrimSpace(existing) == "" {
			return block, nil
		}
		return block + "\n" + existing, nil
	case begin < 0 || end < 0 || end < begin:
		return "", errors.New("AGENTS.md has unbalanced vmono markers; fix or remove them and re-run sync")
	}
	tail := existing[end+len(EndMarker):]
	tail = strings.TrimPrefix(tail, "\r\n")
	tail = strings.TrimPrefix(tail, "\n")
	return existing[:begin] + block + tail, nil
}

// ClaudeMD is the entire content of CLAUDE.md: one line importing AGENTS.md
// so both harnesses read the same text.
const ClaudeMD = "@AGENTS.md\n"

// PackageGitignore renders the package repo's .gitignore. The package repo
// tracks only its own .vmono directory, which holds the manifest, so it
// ignores every other top-level directory: the sessions.
func PackageGitignore() string {
	return "# " + GeneratedNote + "\n/*/\n!/.vmono/\n"
}

// Gitignore renders a session shell repo's .gitignore, ignoring every member
// directory so the repo tracks only generated files and the session file.
func Gitignore(m *manifest.Manifest) string {
	var b strings.Builder
	b.WriteString("# " + GeneratedNote + "\n")
	seen := map[string]bool{}
	for _, mem := range m.Members {
		p := path.Clean(strings.ReplaceAll(mem.Path, `\`, "/"))
		// Ignore the top-level directory; _ref/ covers all reference members.
		top := strings.SplitN(p, "/", 2)[0]
		if !seen[top] {
			seen[top] = true
			b.WriteString("/" + top + "/\n")
		}
	}
	return b.String()
}
